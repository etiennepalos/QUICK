"""Emit the native s/p/d EFG R(t,u,v,0) polynomial helper.

Analytic EFG contractions consume only total degrees 2 through 6. The unchanged
EFIELD generator supplies the Gaussian derivative identity and coefficient
expression. Arithmetic association differs from the iterative recurrence;
the shared caller applies the numerical safety domain and preserves the
reference recurrence for legacy atomics and out-of-domain inputs.
"""
import pathlib
import sys

from generate_oeprop_efield_direct import expression


def render():
    lines = [
        "/*",
        " * (C) Copyright 2026 QUICK contributors",
        " * All rights reserved.",
        " *",
        " * This Source Code Form is subject to the terms of the Mozilla Public",
        " * License, v. 2.0. If a copy of the MPL was not distributed with this",
        " * file, You can obtain one at http://mozilla.org/MPL/2.0/.",
        " */", "",
        "#ifndef __QUICK_GPU_OEPROP_EFG_DIRECT_H_",
        "#define __QUICK_GPU_OEPROP_EFG_DIRECT_H_", "",
        "// Generated by tools/generate_oeprop_efg_direct.py; total degrees 2 through 6 only.",
        "// Native FP64 EFG route; the caller enforces the numerical safety domain.",
        "// Input VY includes Xcoeff_oei and retains the original shell-wide Boys seed.",
        "// Only the m=0 slots consumed by second-derivative contraction are written.",
        "// The common recurrence remains the reference and out-of-domain fallback.",
        "__device__ static inline void oeprop_hermite_coulomb_efg_direct(int order,",
        "        QUICKDouble PCx, QUICKDouble PCy, QUICKDouble PCz, QUICKDouble g,",
        "        QUICKDouble * const YVerticalTemp, QUICKDouble * const store)",
        "{",
        "    QUICKDouble factor = -2.0 * g;",
        "    QUICKDouble A1 = factor * VY(0, 0, 1);",
        "    factor *= -2.0 * g;",
        "    QUICKDouble A2 = factor * VY(0, 0, 2);",
        "    QUICKDouble PCx2 = PCx * PCx;",
        "    QUICKDouble PCy2 = PCy * PCy;",
        "    QUICKDouble PCz2 = PCz * PCz;",
    ]
    for degree in range(2, 7):
        indent = "    " * (degree - 1)
        if degree >= 3:
            lines += ["", "    " * (degree - 2) + f"if (order >= {degree}) {{",
                      indent + "factor *= -2.0 * g;",
                      indent + f"QUICKDouble A{degree} = factor * VY(0, 0, {degree});"]
            for axis in "xyz":
                lines += [indent + f"QUICKDouble PC{axis}{degree} = PC{axis}{degree - 1} * PC{axis};"]
        for t in range(degree, -1, -1):
            for u in range(degree - t, -1, -1):
                v = degree - t - u
                lines += [indent + f"LOCSTORE(store, oeprop_hermite_r_index({t}, {u}, {v}, 0), 0, 1, 1)",
                          indent + "    = " + expression(t, u, v) + ";"]
    for degree in range(6, 2, -1):
        lines += ["    " * (degree - 2) + "}"]
    return "\n".join(lines + ["}", "", "#endif", ""])


if __name__ == "__main__":
    result = render()
    if len(sys.argv) > 2:
        raise SystemExit("usage: generate_oeprop_efg_direct.py [output-header]")
    if len(sys.argv) == 2:
        pathlib.Path(sys.argv[1]).write_text(result)
    else:
        sys.stdout.write(result)
