"""Emit the isolated s/p/d EFIELD R(t,u,v,0) polynomial helper.

Run this script without arguments to print the header.  Supplying one path
writes the same bytes there.  Only total degrees 1..5 are needed: contraction
raises one Cartesian index, and each input shell has angular momentum <= 2.

For A_m=(-2*g)**m * scaled_F_m, the normalized Gaussian derivative identity is
  R_tuv^0 = sum_{a,b,c} C(t,a) C(u,b) C(v,c)
             PCx**(t-2*a) PCy**(u-2*b) PCz**(v-2*c)
             A_(t+u+v-a-b-c),
  C(n,k) = n! / (2**k * k! * (n-2*k)!).
This follows by differentiating exp(-g*|PC|^2) in the Boys integral, or
inductively from R_(t+1)^m = t R_(t-1)^(m+1) + PC R_t^(m+1).
Arithmetic association differs from the original iterative table recurrence;
numerical and CUDA performance validation are required before integration.
"""

import math
import pathlib
import sys


def coefficient(n, k):
    return math.factorial(n) // (2**k * math.factorial(k) * math.factorial(n - 2*k))


def power(axis, exponent):
    if exponent == 0:
        return None
    return f"PC{axis}" if exponent == 1 else f"PC{axis}{exponent}"


def expression(t, u, v):
    terms = []
    for a in range(t//2 + 1):
        for b in range(u//2 + 1):
            for c in range(v//2 + 1):
                integer = coefficient(t, a) * coefficient(u, b) * coefficient(v, c)
                factors = [f"{integer}.0"] if integer != 1 else []
                factors += [p for p in (power("x", t-2*a), power("y", u-2*b),
                                       power("z", v-2*c)) if p]
                factors += [f"A{t+u+v-a-b-c}"]
                terms.append(" * ".join(factors))
    return " + ".join(terms)


def render():
    lines = [
        "/*",
        " * (C) Copyright 2026 QUICK contributors",
        " * All rights reserved.",
        " *",
        " * This Source Code Form is subject to the terms of the Mozilla Public",
        " * License, v. 2.0. If a copy of the MPL was not distributed with this",
        " * file, You can obtain one at http://mozilla.org/MPL/2.0/.",
        " */",
        "",
        "#ifndef __QUICK_GPU_OEPROP_EFIELD_DIRECT_H_",
        "#define __QUICK_GPU_OEPROP_EFIELD_DIRECT_H_",
        "",
        "// Generated by tools/generate_oeprop_efield_direct.py; total degrees 1..5 only.",
        "// EFIELD contracts only R_(t,u,v)^0 with t+u+v >= 1. These direct",
        "// Gaussian-derivative polynomials avoid intermediate auxiliary-order",
        "// scratch traffic. The input VY already contains Xcoeff_oei, and",
        "// production Boys evaluation uses the CPU shell-maximum order,",
        "// Qfinal[II]+Qfinal[JJ]+2 (I+J+2 for pure-angular shells).",
        "// Arithmetic association differs from the iterative Coulomb recurrence.",
        "// Each caller must have 1 <= order <= 5 (s/p/d shell-pair EFIELD).",
        "// Keep the common R index layout; this helper writes only m=0 slots.",
        "__device__ static inline void oeprop_hermite_coulomb_efield_direct(int order,",
        "        QUICKDouble PCx, QUICKDouble PCy, QUICKDouble PCz, QUICKDouble g,",
        "        QUICKDouble * const YVerticalTemp, QUICKDouble * const store)",
        "{",
        "    QUICKDouble factor = -2.0 * g;",
        "    QUICKDouble A1 = factor * VY(0, 0, 1);",
    ]
    for degree in range(1, 6):
        indent = "    " * degree
        if degree >= 2:
            lines += ["", "    " * (degree-1) + f"if (order >= {degree}) {{",
                      indent + "factor *= -2.0 * g;",
                      indent + f"QUICKDouble A{degree} = factor * VY(0, 0, {degree});"]
            for axis in "xyz":
                previous = f"PC{axis}" if degree == 2 else f"PC{axis}{degree-1}"
                lines += [indent + f"QUICKDouble PC{axis}{degree} = {previous} * PC{axis};"]
        for t in range(degree, -1, -1):
            for u in range(degree-t, -1, -1):
                v = degree-t-u
                lines += [indent + f"LOCSTORE(store, oeprop_hermite_r_index({t}, {u}, {v}, 0), 0, 1, 1)",
                          indent + "    = " + expression(t, u, v) + ";"]
    for degree in range(4, 0, -1):
        lines += ["    " * degree + "}"]
    lines += ["}", "", "#endif", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    result = render()
    if len(sys.argv) > 2:
        raise SystemExit("usage: generate_oeprop_efield_direct.py [output-header]")
    if len(sys.argv) == 2:
        pathlib.Path(sys.argv[1]).write_text(result)
    else:
        sys.stdout.write(result)
